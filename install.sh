#!/usr/bin/env bash
# Install Notepad for the current user.
#
# Layout:
#   ~/.local/share/notepad/            application, private venv, icons
#   ~/.local/bin/notepad               command-line launcher
#   ~/.local/share/applications/       menu entry
#   ~/.local/share/icons/hicolor/      application icon
set -euo pipefail

SRC_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
APP_DIR="$DATA_HOME/notepad"
BIN_DIR="$HOME/.local/bin"
BIN_PATH="$BIN_DIR/notepad"
APPLICATIONS_DIR="$DATA_HOME/applications"
DESKTOP_PATH="$APPLICATIONS_DIR/notepad.desktop"
ICON_BASE="$DATA_HOME/icons/hicolor"

info() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }
die() { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

command -v python3 >/dev/null 2>&1 || die "python3 is required. Install it with: sudo pacman -S python"

info "Installing Notepad into $APP_DIR"
mkdir -p "$APP_DIR/icons" "$BIN_DIR" "$APPLICATIONS_DIR" "$ICON_BASE"

install -m 644 "$SRC_DIR/notepad.py" "$APP_DIR/notepad.py"
install -m 644 "$SRC_DIR/requirements.txt" "$APP_DIR/requirements.txt"
install -m 644 "$SRC_DIR/README.md" "$APP_DIR/README.md"
install -m 644 "$SRC_DIR/notepad.desktop.in" "$APP_DIR/notepad.desktop.in"
install -m 644 "$SRC_DIR/icons/notepad.svg" "$APP_DIR/icons/notepad.svg"
install -m 644 "$SRC_DIR/icons/notepad-256.png" "$APP_DIR/icons/notepad-256.png"
install -m 755 "$SRC_DIR/uninstall.sh" "$APP_DIR/uninstall.sh"

VENV="$APP_DIR/venv"
if [ ! -x "$VENV/bin/python" ]; then
    info "Creating a private Python environment"
    if ! python3 -m venv "$VENV"; then
        die "could not create a virtual environment. Install the venv module (Arch: sudo pacman -S python) and try again."
    fi
fi

if ! "$VENV/bin/python" -c 'import PyQt6' >/dev/null 2>&1; then
    info "Installing PyQt6 (this can take a minute)"
    if ! "$VENV/bin/python" -m pip install --disable-pip-version-check --no-input -r "$APP_DIR/requirements.txt"; then
        die "PyQt6 installation failed. Check your network connection, or install the system package (sudo pacman -S python-pyqt6) and run this installer again."
    fi
fi

info "Creating launcher $BIN_PATH"
cat > "$BIN_PATH" <<EOF
#!/bin/sh
# Notepad launcher generated by install.sh
exec "$VENV/bin/python" "$APP_DIR/notepad.py" "\$@"
EOF
chmod 755 "$BIN_PATH"

info "Installing icons"
# xdg-icon-resource only accepts numeric sizes, so install the scalable SVG
# directly and generate the common raster sizes for launchers and panels.
install -Dm644 "$APP_DIR/icons/notepad.svg" "$ICON_BASE/scalable/apps/notepad.svg"

if command -v rsvg-convert >/dev/null 2>&1; then
    for size in 128 64 48 32; do
        rsvg-convert -w "$size" -h "$size" "$APP_DIR/icons/notepad.svg" \
            -o "$APP_DIR/icons/notepad-$size.png"
    done
fi

for size in 256 128 64 48 32; do
    png="$APP_DIR/icons/notepad-$size.png"
    [ -f "$png" ] || continue
    if command -v xdg-icon-resource >/dev/null 2>&1; then
        xdg-icon-resource install --novendor --context apps --size "$size" \
            "$png" notepad
    else
        install -Dm644 "$png" "$ICON_BASE/${size}x${size}/apps/notepad.png"
    fi
done

# Some icon-theme caches require an index.theme in the user's icon directory.
if [ ! -f "$ICON_BASE/index.theme" ] && [ -f /usr/share/icons/hicolor/index.theme ]; then
    install -m 644 /usr/share/icons/hicolor/index.theme "$ICON_BASE/index.theme"
fi

info "Installing desktop entry"
sed "s|@BIN@|$BIN_PATH|g" "$SRC_DIR/notepad.desktop.in" > "$DESKTOP_PATH"
chmod 644 "$DESKTOP_PATH"

if command -v desktop-file-validate >/dev/null 2>&1; then
    if ! desktop-file-validate "$DESKTOP_PATH"; then
        warn "desktop-file-validate reported problems in $DESKTOP_PATH"
    fi
fi

# Refresh the menu and icon caches where the tools are available.
command -v update-desktop-database >/dev/null 2>&1 && \
    update-desktop-database "$APPLICATIONS_DIR" >/dev/null 2>&1 || true
if [ -f "$ICON_BASE/index.theme" ] && command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -f -t "$ICON_BASE" >/dev/null 2>&1 || true
fi

info "Notepad installed successfully."
printf '\n'
printf '  Launch from your application menu, or run:\n'
printf '      notepad [file]\n'
printf '\n'
printf '  Uninstall with:\n'
printf '      %s\n' "$APP_DIR/uninstall.sh"
printf '\n'
